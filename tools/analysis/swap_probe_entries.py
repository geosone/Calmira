#!/usr/bin/env python3
"""Swap two diagnostic FAT16 entries/chains in an offline disposable image.

Never operates on original media: only build/tests/*/prepared.img is accepted.
Both entries must describe identical-size ordinary files generated by replay.
"""
import argparse
from pathlib import Path
import struct

ROOT = Path(__file__).resolve().parents[2]


def main():
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument('image', type=Path)
    parser.add_argument('--mode', required=True, choices=('entries', 'chains'))
    parser.add_argument('--offset', type=int, default=32256)
    args = parser.parse_args()
    image = args.image.resolve()
    if args.image.is_symlink() or not image.is_relative_to(ROOT / 'build/tests') or image.name != 'prepared.img':
        parser.error('only a disposable build/tests/.../prepared.img is allowed')
    if image.stat().st_nlink != 1:
        parser.error('refusing a hard-linked image')
    with image.open('r+b') as stream:
        stream.seek(args.offset)
        boot = stream.read(512)
        size = struct.unpack_from('<H', boot, 11)[0]
        reserved = struct.unpack_from('<H', boot, 14)[0]
        count = struct.unpack_from('<H', boot, 17)[0]
        fat_sectors = struct.unpack_from('<H', boot, 22)[0]
        if size != 512 or not fat_sectors or not 0 < count <= 4096:
            parser.error('unsupported root directory layout')
        root_offset = args.offset + (reserved + boot[16] * fat_sectors) * size
        stream.seek(root_offset)
        directory = stream.read(count * 32)
        records = {}
        for number in range(count):
            entry = directory[number * 32:(number + 1) * 32]
            if entry[:11] in (b'REAL16  EXE', b'OLDREAL EXE') and not entry[11] & 0x18:
                if entry[:11] in records:
                    parser.error('duplicate diagnostic directory entry')
                records[entry[:11]] = (number, entry)
        if len(records) != 2:
            parser.error('expected REAL16.EXE and OLDREAL.EXE in the test copy')
        left_number, left = records[b'REAL16  EXE']
        right_number, right = records[b'OLDREAL EXE']
        if left[28:32] != right[28:32]:
            parser.error('diagnostic files must have equal sizes')
        if args.mode == 'entries':
            first, second = right, left
        else:
            first = left[:26] + right[26:28] + left[28:]
            second = right[:26] + left[26:28] + right[28:]
        print('root entries', left_number, right_number, 'mode', args.mode)
        stream.seek(root_offset + left_number * 32)
        stream.write(first)
        stream.seek(root_offset + right_number * 32)
        stream.write(second)


if __name__ == '__main__':
    main()
